export function buildInitialSnsPosts(presIdeology: number): SnsPost[] {
  const isProgressive = presIdeology < 0;
  const tag = isProgressive ? 'PROG' : 'CONS';
  const filtered = ROWS.filter(r => r[8] === 'ANY' || r[8] === tag);
  return filtered.map((r, i) => ({
    id: genId('post'),
    platform: r[0],
    author: r[1],
    handle: r[2] || undefined,
    content: r[3],
    likes: Math.round(r[4] * 10000),
    reposts: Math.round(r[5] * 10000),
    comments: Math.round(r[6] * 10000),
    sentiment: r[7],
    timestamp: `2025-06-0${(i % 4) + 1}`,
  }));
}
