export function buildSubRegions(): SubRegion[] {
  const out: SubRegion[] = [];
  let seed = 1000;
  // 광역단체장 정당으로 시작, 시군구별 약간 변동 가능
  for (const [region, rows] of ALL_ROWS) {
    for (const r of rows) {
      seed++;
      out.push({
        id: genId('sub'),
        name: r[0],
        parentRegion: region,
        type: r[1],
        population: r[2],
        area: r[3],
        mayor: detName(seed),
        // 80% 광역단체장과 같은 정당, 20% 다른 정당
        mayorParty: det(seed + 13, 100) < 80 ? 'DPK' : 'PPP', // 추후 광역단체장 정당 동기화
        industries: r[4],
        speciality: r[5],
        notable: r[5],
      });
    }
  }
  return out;
}
