function det(seed: number, mod: number): number {
  const x = Math.sin(seed * 9301.7 + 49297.1) * 233280;
  return Math.floor(Math.abs(x - Math.floor(x)) * mod);
}
function detName(seed: number): string {
  return KOREAN_SURNAMES[det(seed, KOREAN_SURNAMES.length)] + KOREAN_GIVEN[det(seed + 17, KOREAN_GIVEN.length)];
}

