export function buildInitialArticles(presIdeology: number): NewsArticle[] {
  const isProgressive = presIdeology < 0;
  const tag = isProgressive ? 'PROG' : 'CONS';
  const filtered = ROWS.filter(r => r[6] === 'ANY' || r[6] === tag);
  return filtered.map((r, i) => ({
    id: genId('art'),
    outlet: r[0],
    headline: r[1],
    lead: r[2],
    body: r[5],
    category: r[3],
    bias: r[4],
    date: `2025-06-0${(i % 4) + 1}`,
  }));
}
